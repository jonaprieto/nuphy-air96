def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def header():
    names = [f"MA_{k[0]}" for k in KEYS]
    lines = [
        "// Generated by tools/math_keys.py; edit the table there.",
        "#pragma once",
        "",
        "enum math_keycodes {",
        f"    {names[0]} = AWAKE_TG + 1,",
        *[f"    {n}," for n in names[1:]],
        "    MA_END",
        "};",
        "",
        "typedef struct {",
        "    const char *uc, *uc_shift, *tex, *tex_shift;",
        "} math_key_t;",
        "",
        "static const math_key_t math_keys[] = {",
        *[
            f"    {{{c_str(u)}, {c_str(us)}, {c_str(t)}, {c_str(ts)}}}, // {k}"
            for k, u, us, t, ts in KEYS
        ],
        "};",
        "",
    ]
    return "\n".join(lines)


def vial_keycodes():
    return [
        {
            "name": f"{u}\n{us}" if us != u else u,
            "title": f"{u} / {us}   {t} / {ts}",
            "shortName": u,
        }
        for _, u, us, t, ts in KEYS
    ]


def main():
    (KEYMAP / "math_keys.h").write_text(header())
    path = KEYMAP / "vial.json"
    vial = json.loads(path.read_text())
    vial["customKeycodes"] = vial["customKeycodes"][:BOARD_KEYCODES] + vial_keycodes()
    path.write_text(json.dumps(vial, indent=2, ensure_ascii=False) + "\n")
    print(f"{len(KEYS)} math keys")


if __name__ == "__main__":
    main()
